"""Build isolated, trace-identified body-animation experiment; not a release."""
from portkit import *
MOVES=[('red_slash',286,247,901,244),('charge_release',212,248,902,147),('moving_spirit',222,249,903,157),('spirit_release',295,250,904,148),('focus_start',460,251,905,144)]
def build(out):
 out=Path(out);out.mkdir(parents=True,exist_ok=True)
 mot=Motlist();clips={mot.clip(o)['name']:mot.clip(o) for o in mot.inventory()}
 _,entries=read_arc(BASE_ARC);original=next(e.data() for e in entries if e.name==ANIM_ENTRY);data=original
 gu,remap=gu_skeleton();rev={r:v for v,r in remap.items()};manifest=[];root_samples=[];attachments=[]
 for label,num,slot,source,template in MOVES:
  clip=clips[f'wp03_00_{num:03}'];frames=int(clip['frames'])+1
  rotations={v:[] for v in remap};rotations[255]=[];positions={0:[],255:[]};roots=[]
  for f in range(frames):
   sw=source_pose(mot,clip,f)
   weapon=np.linalg.inv(sw[mot.by_name['R_Hand']])@sw[mot.by_name['R_Wep']]
   attachments.append([*list(weapon[:3,3]*100),*list(matrixq(weapon))])
   root=sw[mot.by_name['root']][:3,3]*100;roots.append(root)
   desired={v:matrixq(sw[mot.by_name[name]]) for v,name in BODY_MAP.items()}
   for v,r in remap.items():
    parent=gu[r].parent;pq=desired[rev[parent]] if parent is not None else np.array([0,0,0,1])
    rotations[v].append(qnorm(qmul(qinv(pq),desired[v])))
   rotations[255].append([0,0,0,1]);hip=sw[mot.by_name['Hip']][:3,3]*100-root
   positions[0].append(hip);positions[255].append([0,0,0])
  data=Lmt(data).replace(slot,rotations,positions,frames=frames,template=template)
  start=len(root_samples);root_samples.extend([r-roots[0] for r in roots])
  manifest.append(dict(label=label,clip=clip['name'],offset=hex(clip['offset']),slot=slot,source=source,frames=frames,root_offset=start,root_displacement=(roots[-1]-roots[0]).tolist(),status='body playback experiment; grip, hit timing and input integration pending'))
  print(label,clip['name'],slot,frames,flush=True)
 (out/'five.lmt').write_bytes(data);arc_replace(BASE_ARC,out/'five.arc',{ANIM_ENTRY:data})
 # Existing slots must retain the exact descriptor, track bytes and references.
 before=Lmt(original);after=Lmt(data)
 for slot in range(before.count):
  if slot in [x[2] for x in MOVES]:continue
  assert unpack('I',original,8+slot*4)==unpack('I',data,8+slot*4)
  if unpack('I',original,8+slot*4)[0]:assert before.descriptor(slot)==after.descriptor(slot) and before.tracks(slot)[0]==after.tracks(slot)[0]
 header=['/* Generated by build_five.py from user-owned wp03 MOT932. */','#pragma once','typedef struct {unsigned slot,frames,offset;} WildsRootClip;','static const WildsRootClip wilds_root_clips[]={']
 header += [' {%du,%du,%du},'%(x['slot'],x['frames'],x['root_offset']) for x in manifest]
 header += ['};','static const float wilds_root_samples[][3]={']
 header += [' {'+','.join(f'{v:.6f}f' for v in r)+'},' for r in root_samples]
 header += ['};','static const float wilds_weapon_samples[][7]={']
 header += [' {'+','.join(f'{v:.6f}f' for v in a)+'},' for a in attachments]
 header += ['};']
 (out/'wilds_root_data.h').write_text('\n'.join(header)+'\n')
 (out/'manifest.json').write_text(json.dumps({'status':'experimental, not a finished five-move mod','trace':str(PROJECT/'evidence/user-five-moves-trace-20261117.json'),'moves':manifest,'base_sha256':hashlib.sha256(BASE_ARC.read_bytes()).hexdigest(),'arc_sha256':hashlib.sha256((out/'five.arc').read_bytes()).hexdigest()},indent=2))
if __name__=='__main__':
 import sys
