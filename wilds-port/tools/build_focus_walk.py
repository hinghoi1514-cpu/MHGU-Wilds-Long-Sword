"""Build the camera-facing side/back focus cycles into three unused GU slots."""
import argparse
import json
import struct
from pathlib import Path

import numpy as np

from build_combat import retarget
from portkit import ANIM_ENTRY, Lmt, Motlist, arc_replace, gu_skeleton, matrixq, read_arc, source_pose, unpack

WALK_SLOT = 4
DIRECTIONS = (
    ("LEFT", "wp03_00_431_Loop", 222, 0, 1),
    ("RIGHT", "wp03_00_432_Loop", 223, 0, -1),
    ("BACK", "wp03_00_433_Loop", 254, 2, -1),
)


def build(base, out):
    out.mkdir(parents=True, exist_ok=True)
    _, entries = read_arc(base)
    original = next(e.data() for e in entries if e.name == ANIM_ENTRY)
    data = original
    native = Lmt(original)
    native_frames, _ = native.tracks(WALK_SLOT)
    stride = unpack("f", native.descriptor(WALK_SLOT), 24)[0] / (native_frames - 1)
    mot = Motlist()
    clips = {c["name"]: c for c in (mot.clip(offset) for offset in mot.inventory())}
    bones, remap = gu_skeleton()
    reverse = {r: v for v, r in remap.items()}
    root_index, hand_index, weapon_index = (mot.by_name[name] for name in ("root", "R_Hand", "R_Wep"))
    manifest, attachments = [], []
    for label, name, slot, axis, sign in DIRECTIONS:
        assert struct.unpack_from("<I", original, 8 + 4 * slot)[0] == 0, slot
        clip = clips[name]
        duration = clip["frames"]
        start_root = source_pose(mot, clip, 0)[root_index][:3, 3]
        end_root = source_pose(mot, clip, duration)[root_index][:3, 3]
        distance = (end_root[axis] - start_root[axis]) * sign * 100
        assert distance > 0
        frames = round(distance / stride) + 1
        rotations = {joint: [] for joint in remap}
        positions = {0: [], 255: []}
        offset = len(attachments)
        for time in np.linspace(0, duration, frames):
            transform = source_pose(mot, clip, time)
            pose, hip, _ = retarget(mot, transform, bones, remap, reverse)
            for joint, rotation in pose.items():
                rotations[joint].append(rotation)
            positions[0].append(hip)
            # The native root is evaluated in the travel heading. The
            # body and its weapon are evaluated in the camera heading.
            travel = (transform[root_index][axis, 3] - start_root[axis]) * sign * 100
            positions[255].append((0, 0, travel))
            weapon = np.linalg.inv(transform[hand_index]) @ transform[weapon_index]
            attachments.append([*(weapon[:3, 3] * 100), *matrixq(weapon)])
        data = bytearray(Lmt(data).replace(slot, rotations, positions, frames=frames, template=WALK_SLOT))
        descriptor = unpack("I", data, 8 + 4 * slot)[0]
        struct.pack_into("<f", data, descriptor + 24, distance)
        # The original forward walk events are specific to its footfalls.
        struct.pack_into("<I", data, descriptor + 52, 0)
        manifest.append(dict(direction=label, name=name, slot=slot, frames=frames, offset=offset, stride=distance))

    for slot in range(native.count):
        if slot not in {item["slot"] for item in manifest}:
            assert unpack("I", data, 8 + 4 * slot) == unpack("I", original, 8 + 4 * slot)
    arc_replace(base, out / "w07.arc", {ANIM_ENTRY: data})
    header = ["/* Generated by build_focus_walk.py. */", "#pragma once"]
    header += [f'enum {{FOCUS_WALK_{m["direction"]}={m["slot"]}}};' for m in manifest]
    header += ["static const WildsClip focus_walk_clips[]={"]
    header += [f' {{.slot={m["slot"]},.frames={m["frames"]},.offset={m["offset"]}}},' for m in manifest]
    header += ["};", "static const float focus_walk_weapon_samples[][7]={"]
    header += [" {" + ",".join(f"{v:.6f}f" for v in sample) + "}," for sample in attachments]
    header += ["};"]
    (out / "focus_walk_data.h").write_text("\n".join(header) + "\n")
    (out / "focus-walk-assets.json").write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("base", type=Path)
    parser.add_argument("out", type=Path)
    args = parser.parse_args()
    build(args.base, args.out)
